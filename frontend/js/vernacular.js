class VernacularManager {
  constructor() {
    this.currentLang = localStorage.getItem('e_setu_lang') || 'hi';
  }

  setLanguage(lang) {
    if (VERNACULAR_DICT[lang]) {
      this.currentLang = lang;
      localStorage.setItem('e_setu_lang', lang);
      document.dispatchEvent(new CustomEvent('language_changed', { detail: { lang } }));
      this.updateDOM();
    }
  }

  t(key) {
    return VERNACULAR_DICT[this.currentLang][key] || VERNACULAR_DICT['hi'][key] || key;
  }

  updateDOM() {
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (key && VERNACULAR_DICT[this.currentLang][key]) {
        el.textContent = VERNACULAR_DICT[this.currentLang][key];
      }
    });

    // Update active state in language selector buttons
    document.querySelectorAll('.lang-btn').forEach((btn) => {
      const lang = btn.getAttribute('data-lang');
      if (lang === this.currentLang) {
        btn.classList.add('active');
      } else {
        btn.classList.remove('active');
      }
    });
  }
}

window.vernacular = new VernacularManager();
